/**
 * Generates the component documentation pages in docs/components from the ui registry.
 *
 * Usage: node scripts/generate-component-docs.mjs [--check]
 *   --check  verify every generated page matches disk without writing; exits 1 on drift.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { join, resolve } from "node:path";
import { format as formatWithPrettier, resolveConfig as resolvePrettierConfig } from "prettier";

const root = resolve(import.meta.dirname, "..");
const registrySource = readFileSync(join(root, "src/components/ui/registry.ts"), "utf8");
const names = [...registrySource.matchAll(/\s+"([^"]+)",/g)].map((match) => match[1]);
const outputDirectory = join(root, "docs/components");

const slugify = (name) =>
  name
    .replace(/([a-z])([A-Z])/g, "$1-$2")
    .replace(/\s+/g, "-")
    .toLowerCase();

const componentIdentifier = (name) => name.replace(/\s+/g, "");

const categoryFor = (name) => {
  if (/Dialog|Drawer|Sheet|Popover|Hover Card/.test(name)) return "overlays";
  if (/Input|Checkbox|Combobox|Date Picker|Field|Label|Radio|Select|Slider|Switch|Textarea/.test(name)) {
    return "forms";
  }
  if (/Button|Toggle/.test(name)) return "actions";
  if (/Alert|Badge|Marker|Progress|Spinner|Toast|Tooltip/.test(name)) return "feedback";
  if (/Menu|Breadcrumb|Command|Kbd|Navigation|Pagination|Tabs/.test(name)) return "navigation";
  return "content";
};

// Generate every page in memory so `--check` can compare against disk without writing.
const contents = new Map();

for (const name of names) {
  const slug = slugify(name);
  const identifier = componentIdentifier(name);
  const source = `src/components/ui/${slug}.tsx`;
  const body = `<!-- Generated by scripts/generate-component-docs.mjs. Keep this page source-linked. -->
# ${name}

`;
  const content = `${body}## Purpose

${name} is a ${categoryFor(name)} primitive in the Kinetic UI source-copy library. Use it when you need the same semantic behavior and Skeuomorphic material tokens as the showcase.

## Install or copy

Copy [\`${source}\`](../../${source}) and the shared token stylesheet. The component is also available from the public barrel at [\`src/components/ui/index.ts\`](../../src/components/ui/index.ts).

## Usage sketch

\`\`\`tsx
import * as ComponentSource from "@/components/ui/${slug}";

// Use the exported ${identifier} component with the props defined in the source file.
export { ComponentSource };
\`\`\`

This import sketch is intentionally source-safe for primitives with required props or compound parts. Consult the exported types and example in [\`src/catalog\`](../../src/catalog) rather than creating a second implementation.

## API and variants

The source file is the API contract. Read its exported prop types for events, controlled values, variants, sizes, and forwarded refs. Keep \`className\` composition through the shared \`cn\` helper and preserve the semantic element used by the primitive.

## Accessibility and interaction

Use the component with an accessible name and keep its keyboard behavior intact. Focus must remain visible, Escape should dismiss dismissible overlays, and disabled controls must not activate. The shared behavior tests in [\`src/components/ui/ui-behaviors.test.tsx\`](../../src/components/ui/ui-behaviors.test.tsx) are the reference for expected interaction.

## States and responsive behavior

Document any loading, disabled, error, and success state added by the consuming application. Verify both light and dark materials, reduced motion, narrow viewports, and 200% zoom before shipping.

## Example and ownership

- Category: **${categoryFor(name)}**
- Canonical example: [\`${slugify(name)}\`](../../src/registry/componentMetadata.ts)
- Source: [\`${source}\`](../../${source})
- Dependencies: React and Kinetic UI tokens (plus imports listed by the source file)
`;
  contents.set(join(outputDirectory, `${slug}.md`), content);
}

// Generated pages are committed through prettier, so format the in-memory copies the same way.
const prettierOptions = (await resolvePrettierConfig(join(outputDirectory, "placeholder.md"))) ?? {};
for (const [path, content] of [...contents]) {
  contents.set(path, await formatWithPrettier(content, { ...prettierOptions, parser: "markdown" }));
}

const checkOnly = process.argv.includes("--check");

if (checkOnly) {
  const drifted = [];
  for (const [path, expected] of contents) {
    let actual;
    try {
      actual = readFileSync(path, "utf8").replace(/\r\n/g, "\n");
    } catch {
      actual = null;
    }
    if (actual !== expected) drifted.push(path.replace(root, "."));
  }
  if (drifted.length > 0) {
    console.error(`[docs] Drift detected in ${drifted.length} generated file(s):`);
    for (const file of drifted) console.error(`  - ${file}`);
    console.error('Run "npm run docs:components" and commit the regenerated files.');
    process.exit(1);
  }
  console.log(`[docs] Generated component docs are up to date (${names.length} pages).`);
} else {
  mkdirSync(outputDirectory, { recursive: true });
  for (const [path, content] of contents) writeFileSync(path, content);
  const prettier = join(root, "node_modules/prettier/bin/prettier.cjs");
  execFileSync(process.execPath, [prettier, "--write", "docs/components"], { cwd: root, stdio: "ignore" });
  console.log(`Generated ${names.length} component documentation pages.`);
}
